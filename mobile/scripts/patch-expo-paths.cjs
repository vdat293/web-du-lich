const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const podspecPath = path.join(
  projectRoot,
  'node_modules/expo-constants/ios/EXConstants.podspec',
);
const scriptPath = path.join(
  projectRoot,
  'node_modules/expo-constants/scripts/get-app-config-ios.sh',
);
const iosProjectPath = path.join(
  projectRoot,
  'ios/Aoklevart.xcodeproj/project.pbxproj',
);

function replaceOnce(filePath, original, replacement) {
  const source = fs.readFileSync(filePath, 'utf8');
  if (source.includes(replacement)) return;
  if (!source.includes(original)) {
    throw new Error(`Không tìm thấy mẫu Expo SDK 54 cần vá trong ${filePath}`);
  }
  fs.writeFileSync(filePath, source.replace(original, replacement));
}

// Expo SDK 54 passes an unquoted path as the command string to `bash -c`.
// That fails whenever the project path contains spaces. Invoke the script
// directly and quote its path instead.
replaceOnce(
  podspecPath,
  ':script => "bash -l -c \\"#{env_vars}$PODS_TARGET_SRCROOT/../scripts/get-app-config-ios.sh\\"",',
  ':script => "#{env_vars}bash \\"$PODS_TARGET_SRCROOT/../scripts/get-app-config-ios.sh\\"",',
);

replaceOnce(
  scriptPath,
  'PROJECT_DIR_BASENAME=$(basename $PROJECT_DIR)',
  'PROJECT_DIR_BASENAME=$(basename "$PROJECT_DIR")',
);

// The checked-in native project was generated by an older Expo template. Its
// command substitution is executed as shell source, so paths containing spaces
// are split before React Native's build script can start.
if (fs.existsSync(iosProjectPath)) {
  replaceOnce(
    iosProjectPath,
    '`\\"$NODE_BINARY\\" --print \\"require(\'path\').dirname(require.resolve(\'react-native/package.json\')) + \'/scripts/react-native-xcode.sh\'\\"`',
    'REACT_NATIVE_XCODE=\\"$(\\"$NODE_BINARY\\" --print \\"require(\'path\').dirname(require.resolve(\'react-native/package.json\')) + \'/scripts/react-native-xcode.sh\'\\")\\"\\n\\"$REACT_NATIVE_XCODE\\"',
  );
}

console.log('Patched Expo iOS scripts for project paths containing spaces.');
